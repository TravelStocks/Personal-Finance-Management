const increasedInvestment=normalize({...bonusPlan,rows:bonusPlan.rows.map(row=>row.id==='investment'?{...row,normal:3000,trip:3000}:row)});
assert.equal(accumulate(increasedInvestment).projectedAccumulation,90050,'Moving cash to investment changes the composition, never the total accumulation');
assert.equal(accumulate(increasedInvestment).projectedCash,54050);
assert.equal(accumulate({...baseline,paidDays:0, salary:11000},10000).projectedCash,-7100,'A funding deficit is shown instead of falsely promising cash savings');

